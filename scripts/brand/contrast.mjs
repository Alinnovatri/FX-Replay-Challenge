#!/usr/bin/env node
// Measures WCAG 2.x contrast for the generated brand tokens and writes docs/brand/CONTRAST.md.
//
//   node scripts/brand/contrast.mjs          write the report
//   node scripts/brand/contrast.mjs --check  exit 1 if the committed report is stale

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TOKENS = join(ROOT, 'brand', 'generated', 'tokens.json');
const OUT = join(ROOT, 'docs', 'brand', 'CONTRAST.md');

export function luminance(hex) {
  const channels = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const [r, g, b] = channels.map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

export const textVerdict = (ratio) => (ratio >= 4.5 ? 'AA' : ratio >= 3 ? 'AA large only' : 'Fail');
export const nonTextVerdict = (ratio) => (ratio >= 3 ? 'Pass' : 'Fail');

/** Resolves a primitive or semantic token name to a hex value; fails on unknown or translucent tokens. */
export function resolver(tokens) {
  const { primitive, semantic } = tokens.color;
  return (name) => {
    if (primitive[name]) return primitive[name].$value;
    const token = semantic[name];
    if (!token) throw new Error(`contrast: unknown token "${name}"`);
    if (token.$extensions.alpha !== undefined)
      throw new Error(`contrast: "${name}" is translucent; measure it composited`);
    const ref = token.$value.match(/^\{color\.primitive\.([a-z0-9-]+)\}$/)?.[1];
    if (!ref || !primitive[ref]) throw new Error(`contrast: "${name}" has an unresolvable value ${token.$value}`);
    return primitive[ref].$value;
  };
}

const SURFACES = ['bg-primary', 'bg-secondary', 'bg-tertiary'];
const TEXT = [
  'text-primary',
  'text-secondary',
  'text-disabled',
  'text-brand',
  'text-error',
  'text-warning',
  'text-success',
  'card-text-secondary',
  'btn-text-minimal-hover',
];
// Primitives worth considering for text on dark surfaces where the semantic token falls short.
const CANDIDATES = ['blue-400', 'blue-500', 'error', 'warning', 'success'];
const BUTTONS = [
  ['btn-text', 'btn-bg-primary-active'],
  ['btn-text', 'btn-bg-primary-hover'],
  ['btn-text', 'btn-bg-primary-pressed'],
  ['btn-text-disabled', 'btn-bg-primary-disabled'],
  ['btn-text', 'btn-bg-secondary-active'],
  ['btn-text', 'btn-bg-secondary-hover'],
  ['btn-text-disabled', 'btn-bg-secondary-disabled'],
  ['banner-color-paragraph', 'banner-bg-error'],
  ['banner-color-paragraph', 'banner-bg-warning'],
  ['banner-color-paragraph', 'banner-bg-success'],
  ['banner-color-paragraph', 'banner-bg-info'],
];
const BOUNDARIES = [
  'border-primary',
  'border-secondary',
  'border-tertiary',
  'btn-border-outline',
  'border-brand',
  'border-error',
];

export function renderReport(tokens) {
  const hex = resolver(tokens);
  const cell = (fg, bg) => {
    const ratio = contrast(hex(fg), hex(bg));
    return `${ratio.toFixed(2)} ${textVerdict(ratio)}`;
  };
  const header = (cols) => [`| ${cols.join(' | ')} |`, `| ${cols.map(() => '---').join(' | ')} |`];

  const lines = [
    '# Brand contrast report',
    '',
    'Generated by `scripts/brand/contrast.mjs` from `brand/generated/tokens.json`. Do not edit by hand.',
    '',
    'Thresholds (WCAG 2.2): text AA needs 4.5:1, large text (24 px, or 18.66 px bold) needs 3:1,',
    'and non-text boundaries such as input borders need 3:1 against the adjacent color (SC 1.4.11).',
    '',
    '## Text on surfaces',
    '',
    ...header(['Foreground', ...SURFACES.map((s) => `${s} (${hex(s)})`)]),
  ];
  for (const fg of [...TEXT, ...CANDIDATES]) {
    const label = CANDIDATES.includes(fg) ? `${fg} (primitive)` : fg;
    lines.push(`| ${label} \`${hex(fg)}\` | ${SURFACES.map((bg) => cell(fg, bg)).join(' | ')} |`);
  }

  lines.push('', '## Buttons and banners', '', ...header(['Text', 'Background', 'Ratio']));
  for (const [fg, bg] of BUTTONS) {
    lines.push(`| ${fg} \`${hex(fg)}\` | ${bg} \`${hex(bg)}\` | ${cell(fg, bg)} |`);
  }

  lines.push('', '## Boundaries against bg-primary (non-text, 3:1)', '', ...header(['Token', 'Ratio', 'Verdict']));
  for (const token of BOUNDARIES) {
    const ratio = contrast(hex(token), hex('bg-primary'));
    lines.push(`| ${token} \`${hex(token)}\` | ${ratio.toFixed(2)} | ${nonTextVerdict(ratio)} |`);
  }

  const skipped = Object.entries(tokens.color.semantic)
    .filter(([, t]) => t.$extensions.alpha !== undefined)
    .map(([k]) => `\`${k}\``);
  if (skipped.length)
    lines.push('', `Not measured (translucent, depends on what is behind it): ${skipped.join(', ')}.`);
  return lines.join('\n') + '\n';
}

function main(argv) {
  const report = renderReport(JSON.parse(readFileSync(TOKENS, 'utf8')));
  if (argv.includes('--check')) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== report) {
      console.error('Stale contrast report: docs/brand/CONTRAST.md. Run: node scripts/brand/contrast.mjs');
      process.exit(1);
    }
    console.log('Contrast report is up to date.');
    return;
  }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, report);
  console.log('Wrote docs/brand/CONTRAST.md');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
